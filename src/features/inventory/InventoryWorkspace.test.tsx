import { afterEach, expect, test, vi } from 'vitest';
import { cleanup, render, screen, waitFor } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import InventoryWorkspace from './InventoryWorkspace';
import { loadInventory, saveInventory } from '../../storage/inventory';
import { parseInventory } from '../../domain/inventory';
vi.mock('../../storage/inventory', () => ({ loadInventory: vi.fn(), saveInventory: vi.fn() }));
afterEach(cleanup);
const fixture = { source: 'HSR-Scanner', version: 4, relics: Array.from({ length: 100 }, (_, i) => ({ _uid: String(i), set_id: '102', name: 'Musketeer of Wild Wheat', slot: 'Hands', rarity: 5, level: 15, mainstat: 'ATK', substats: [{ key: 'SPD', value: 2 }], location: '', lock: false, discard: i === 0 })) };
test('file preview requires confirmation, persistence failure keeps previous inventory, retry succeeds', async () => {
  vi.mocked(loadInventory).mockResolvedValue(null);
  vi.mocked(saveInventory).mockRejectedValueOnce(new Error('Storage full')).mockResolvedValueOnce();
  const user = userEvent.setup(); const activated = vi.fn();
  render(<InventoryWorkspace visible onInventory={activated} />);
  const input = screen.getByLabelText('Import scanner JSON or Orbit backup');
  await waitFor(() => expect((input as HTMLInputElement).disabled).toBe(false));
  const file = new File(['fixture'], 'scan.json', { type: 'application/json' });
  Object.defineProperty(file, 'text', { value: async () => JSON.stringify(fixture) });
  await user.upload(input, file);
  expect(activated).not.toHaveBeenCalled();
  await user.click(screen.getByRole('button', { name: 'Replace inventory' }));
  expect(await screen.findByRole('alert')).toHaveProperty('textContent', 'Storage full');
  expect(activated).not.toHaveBeenCalled();
  await user.click(screen.getByRole('button', { name: 'Replace inventory' }));
  await screen.findByText('100 of 100 imported relics');
  expect(activated).toHaveBeenCalledTimes(1);
  expect(screen.getAllByRole('button', { pressed: false })).toHaveLength(48);
  await user.click(screen.getByRole('button', { name: 'Next page' }));
  expect(screen.getByText('Page 2 of 3')).toBeTruthy();
  await user.selectOptions(screen.getByLabelText('Inventory status'), 'discarded');
  expect(screen.getByText('1 of 100 imported relics')).toBeTruthy();
  expect(screen.getByText('Page 1 of 1')).toBeTruthy();
  const invalid = new File(['bad'], 'bad.json', { type: 'application/json' });
  Object.defineProperty(invalid, 'text', { value: async () => '{' });
  await user.upload(input, invalid);
  expect(await screen.findByRole('alert')).toHaveProperty('textContent', 'File: invalid JSON');
  expect(screen.getByText('1 of 100 imported relics')).toBeTruthy();
});
test('restores saved inventory and cancels a valid replacement without saving', async () => {
  vi.mocked(loadInventory).mockResolvedValue(parseInventory(JSON.stringify(fixture)));
  vi.mocked(saveInventory).mockClear();
  const user = userEvent.setup();
  render(<InventoryWorkspace visible onInventory={() => {}} />);
  await screen.findByText('100 of 100 imported relics');
  const file = new File(['empty'], 'empty.json', { type: 'application/json' });
  Object.defineProperty(file, 'text', { value: async () => JSON.stringify({ ...fixture, relics: [] }) });
  await user.upload(screen.getByLabelText('Import scanner JSON or Orbit backup'), file);
  await user.click(screen.getByRole('button', { name: 'Cancel import' }));
  expect(saveInventory).not.toHaveBeenCalled();
  expect(screen.getByText('100 of 100 imported relics')).toBeTruthy();
});
test('ten thousand relics remain paginated while catalogue filters compose and reset', async () => {
  const large = { ...fixture, characters: [{ id: '1308', name: 'Acheron' }], relics: Array.from({length:10000}, (_,i) => ({ ...fixture.relics[0], _uid:String(i), level:i % 16, set_id:i % 2 ? '117' : '102', location:'1308' })) };
  vi.mocked(loadInventory).mockResolvedValue(parseInventory(JSON.stringify(large)));
  render(<InventoryWorkspace visible onInventory={() => {}} />);
  await screen.findByText('10000 of 10000 imported relics');
  expect(screen.getAllByRole('button', {pressed:false})).toHaveLength(48);
  const user = userEvent.setup();
  await user.selectOptions(screen.getByLabelText('Minimum level'), '15');
  await user.selectOptions(screen.getByLabelText('Relic set'), '117');
  await user.selectOptions(screen.getByLabelText('Main stat'), 'ATK');
  await user.selectOptions(screen.getByLabelText('Rarity'), '5');
  await user.selectOptions(screen.getByLabelText('Equipped character'), '1308');
  expect(screen.getByText('625 of 10000 imported relics')).toBeTruthy();
  expect(screen.getByText('Page 1 of 14')).toBeTruthy();
  await user.click(screen.getByRole('button', {name:'Reset inventory filters'}));
  expect(screen.getByText('10000 of 10000 imported relics')).toBeTruthy();
});
