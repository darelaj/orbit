test('editing B preserves A, deltas update, and failed saves do not claim success',async()=>{
  vi.mocked(loadComparisons).mockResolvedValue([]);
  vi.mocked(saveComparisons).mockRejectedValueOnce(new Error('Storage unavailable')).mockResolvedValueOnce();
  const inventory=parseInventory(JSON.stringify({source:'HSR-Scanner',version:4,characters:[{id:'1308',name:'Acheron'}],relics:[1,2].map(i=>({_uid:String(i),set_id:'102',name:'Musketeer',slot:'Head',rarity:5,level:i===1?0:15,mainstat:'HP',substats:[],location:i===1?'1308':'',lock:false,discard:false}))}));
  const user=userEvent.setup();render(<ComparisonWorkspace inventory={inventory}/>);
  await user.selectOptions(screen.getByLabelText('Initialize from imported character'),'1308');
  await user.click(screen.getByRole('button',{name:'Initialize A and B'}));
  const speed=screen.getByLabelText('Character base SPD');await user.clear(speed);await user.type(speed,'100');
  await user.click(screen.getByRole('button',{name:'Use Head relic 2 in B'}));
  expect(within(screen.getByRole('region',{name:'Reference A'})).getByText(/ID 1/)).toBeTruthy();
  expect(within(screen.getByRole('region',{name:'Candidate B'})).getByText(/ID 2/)).toBeTruthy();
  expect(screen.getByText('+592.704')).toBeTruthy();
  await user.type(screen.getByLabelText('Snapshot name'),'Test pair');
  await user.click(screen.getByRole('button',{name:'Save comparison'}));
  expect(await screen.findByRole('alert')).toHaveProperty('textContent','Storage unavailable');
  expect(screen.queryByRole('button',{name:'Load Test pair'})).toBeNull();
  await user.click(screen.getByRole('button',{name:'Save comparison'}));
  await screen.findByRole('button',{name:'Load Test pair'});
  await user.click(screen.getByRole('button',{name:'Clear B Head'}));
  expect(within(screen.getByRole('region',{name:'Candidate B'})).queryByText(/ID 2/)).toBeNull();
  await user.click(screen.getByRole('button',{name:'Load Test pair'}));
  expect(within(screen.getByRole('region',{name:'Candidate B'})).getByText(/ID 2/)).toBeTruthy();
  await user.click(screen.getByRole('button',{name:'Reset B to A'}));
  expect(within(screen.getByRole('region',{name:'Candidate B'})).getByText(/ID 1/)).toBeTruthy();
});
