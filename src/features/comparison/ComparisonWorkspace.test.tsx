import {afterEach,expect,test,vi} from 'vitest';
import {cleanup,render,screen,within} from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import ComparisonWorkspace from './ComparisonWorkspace';
import {loadComparisons,saveComparisons} from '../../storage/comparison';
import {parseInventory} from '../../domain/inventory';
import characterFixture from '../../../tests/fixtures/character-export.json';
vi.mock('../../storage/comparison',()=>({loadComparisons:vi.fn(),saveComparisons:vi.fn(),decodeComparisons:vi.fn(),encodeComparisons:vi.fn()}));
afterEach(cleanup);

test('catalogue initialization includes unequipped roster, marks manual edits and protects existing drafts',async()=>{
  vi.mocked(loadComparisons).mockResolvedValue([]);
  vi.mocked(saveComparisons).mockResolvedValue();
  const raw=structuredClone(characterFixture);
  const traces=raw.characters[0].traces; if(!traces)throw new Error('Missing synthetic Trace fixture');
  for(const key of Object.keys(traces)) if(key!=='secret')Reflect.set(traces,key,false);
  const inventory=parseInventory(JSON.stringify({...raw,characters:[raw.characters[0],{...raw.characters[0],id:'1001',name:'March 7th',path:'Preservation'}]}));
  const user=userEvent.setup();const view=render(<ComparisonWorkspace inventory={inventory}/>);
  const select=screen.getByLabelText('Initialize from imported character');
  await user.selectOptions(select,'1308');
  await user.click(screen.getByLabelText('Use pinned baseline kit'));
  await user.selectOptions(screen.getByLabelText('Profile Light Cone'),'none');
  await user.click(screen.getByRole('button',{name:'Initialize A and B'}));
  expect(screen.getByLabelText('Character base SPD')).toHaveProperty('value','101');
  expect(screen.getByLabelText('Character/profile name')).toHaveProperty('value','Acheron');
  expect(screen.getByText(/Profile source: Pinned baseline/)).toBeTruthy();
  const speed=screen.getByLabelText('Character base SPD');await user.clear(speed);await user.type(speed,'105');
  expect(screen.getByText(/Profile source: Edited baseline/)).toBeTruthy();
  await user.type(screen.getByLabelText('Snapshot name'),'Automatic fixture');
  await user.click(screen.getByRole('button',{name:'Save comparison'}));
  expect(vi.mocked(saveComparisons).mock.lastCall?.[0][0].profile.origin?.mode).toBe('edited');
  await user.selectOptions(select,'1001');
  await user.click(screen.getByLabelText('Use pinned baseline kit'));
  await user.selectOptions(screen.getByLabelText('Profile Light Cone'),'none');
  await user.click(screen.getByRole('button',{name:'Initialize A and B'}));
  expect(screen.getByLabelText('Character base SPD')).toHaveProperty('value','105');
  await user.click(screen.getByRole('button',{name:'Keep editing'}));
  expect(screen.getByLabelText('Character/profile name')).toHaveProperty('value','Acheron');
  await user.click(screen.getByRole('button',{name:'Initialize A and B'}));
  await user.click(screen.getByRole('button',{name:'Replace drafts'}));
  expect(screen.getByLabelText('Character/profile name')).toHaveProperty('value','March 7th');
  expect(screen.getByLabelText('Character base SPD')).toHaveProperty('value','101');
  await user.click(screen.getByRole('button',{name:'Load Automatic fixture'}));
  expect(screen.getByLabelText('Character base SPD')).toHaveProperty('value','105');
  expect(screen.getByText(/Profile source: Edited baseline/)).toBeTruthy();
  await user.click(screen.getByRole('button',{name:'Initialize A and B'}));
  expect(screen.getByRole('button',{name:'Replace drafts'})).toBeTruthy();
  view.rerender(<ComparisonWorkspace inventory={{...inventory,importedAt:'2026-11-08T00:00:00.000Z'}}/>);
  expect(screen.queryByRole('button',{name:'Replace drafts'})).toBeNull();
  expect(screen.getByLabelText('Use pinned baseline kit')).toHaveProperty('checked',false);
  expect(screen.getByLabelText('Character base SPD')).toHaveProperty('value','105');
});

