import {afterEach,expect,test,vi} from 'vitest';
import {cleanup,render,screen,within} from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import SpeedWorkspace from './SpeedWorkspace';
import {loadTeam,saveTeam} from '../../storage/speed';
import {defaultTeam} from '../../domain/speed';
vi.mock('../../storage/speed',()=>({loadTeam:vi.fn(),saveTeam:vi.fn(),MAX_TEAM_BYTES:16384,decodeTeam:vi.fn(),encodeTeam:vi.fn()}));
afterEach(cleanup);
test('copying comparison B resets buffs, preserves precision and snapshots values without live relinking',async()=>{
  vi.mocked(loadTeam).mockResolvedValue(null);vi.mocked(saveTeam).mockRejectedValueOnce(new Error('Storage full')).mockResolvedValueOnce();
  const user=userEvent.setup();const source={name:'Manual B',baseSPD:100,panelSPD:133.33333333333334,precision:'ocr' as const};
  const {rerender}=render(<SpeedWorkspace source={source}/>);
  const copy=screen.getByRole('button',{name:'Use comparison B SPD'});
  await user.click(copy);
  const one=within(screen.getByRole('region',{name:'Speed member 1'}));
  expect(one.getByText('ocr · Comparison B · Manual B')).toBeTruthy();
  expect(one.getByLabelText('Member 1 panel SPD')).toHaveProperty('valueAsNumber',source.panelSPD);
  rerender(<SpeedWorkspace source={{...source,panelSPD:150}}/>);
  expect(one.getByLabelText('Member 1 panel SPD')).toHaveProperty('valueAsNumber',source.panelSPD);
  await user.type(one.getByLabelText('Member 1 additional flat SPD'),'5');
  await user.click(copy);expect(one.getByLabelText('Member 1 additional flat SPD')).toHaveProperty('value','0');
  await user.clear(one.getByLabelText('Member 1 panel SPD'));await user.type(one.getByLabelText('Member 1 panel SPD'),'140');
  expect(one.getByText('manual · Manual input')).toBeTruthy();
  await user.click(screen.getByRole('button',{name:'Save team'}));
  expect(await screen.findByRole('alert')).toHaveProperty('textContent','Storage full');
  await user.click(screen.getByRole('button',{name:'Save team'}));
  expect(await screen.findByText('Team configuration saved in this browser.')).toBeTruthy();
});
test('restores saved team, rejects transient invalid inputs and paginates the action ledger',async()=>{
  const team=defaultTeam();team.cycles=20;vi.mocked(loadTeam).mockResolvedValue(team);
  const user=userEvent.setup();render(<SpeedWorkspace source={null}/>);
  await screen.findByText('Saved team restored from this browser.');
  expect(screen.getByText('Chronological actions · page 1 of 2')).toBeTruthy();
  await user.click(screen.getByRole('button',{name:'Next actions'}));
  expect(screen.getByText('Chronological actions · page 2 of 2')).toBeTruthy();
  await user.clear(screen.getByLabelText('Member 1 base SPD'));
  expect(screen.getByRole('alert').textContent).toContain('finite');
  expect(screen.queryByRole('region',{name:'Chronological action ledger'})).toBeNull();
  await user.click(screen.getByRole('button',{name:'Reset team inputs'}));
  expect(screen.getByText('Chronological actions · page 1 of 1')).toBeTruthy();
});
